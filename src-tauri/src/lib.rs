use base64::Engine;
use serde::Serialize;
use std::{fs, path::PathBuf, process::Command, time::{SystemTime, UNIX_EPOCH}};
use tauri::Manager;

#[derive(Serialize)]
struct EngineStatus { ready: bool, details: String }

fn engine_path(app: &tauri::AppHandle, name: &str) -> Result<PathBuf, String> {
    let path = app.path().resource_dir().map_err(|e| e.to_string())?.join("resources").join("engines").join(name);
    if !path.is_file() { return Err(format!("Bundled processing component is missing: {}", name)); }
    Ok(path)
}

#[tauri::command]
fn transcription_engine_status(app: tauri::AppHandle) -> EngineStatus {
    let required = ["ffmpeg.exe", "ffprobe.exe", "whisper-cli.exe", "ggml-base.en.bin"];
    let missing: Vec<_> = required.iter().filter(|name| engine_path(&app, name).is_err()).copied().collect();
    if missing.is_empty() { EngineStatus { ready: true, details: "Local transcription tools and English speech model are installed.".into() } }
    else { EngineStatus { ready: false, details: format!("Missing bundled components: {}. Rebuild the installer using the Windows workflow.", missing.join(", ")) } }
}

#[tauri::command]
async fn transcribe_local(app: tauri::AppHandle, file_name: String, file_base64: String) -> Result<String, String> {
    tauri::async_runtime::spawn_blocking(move || {
        let ffmpeg = engine_path(&app, "ffmpeg.exe")?;
        let whisper = engine_path(&app, "whisper-cli.exe")?;
        let model = engine_path(&app, "ggml-base.en.bin")?;
        let base = std::env::temp_dir().join(format!("odaa-transcribe-{}-{}", std::process::id(), SystemTime::now().duration_since(UNIX_EPOCH).map_err(|e| e.to_string())?.as_nanos()));
        fs::create_dir_all(&base).map_err(|e| e.to_string())?;
        let result = (|| {
            let extension = std::path::Path::new(&file_name).extension().and_then(|e| e.to_str()).unwrap_or("media");
            if !extension.chars().all(|c| c.is_ascii_alphanumeric()) { return Err("Invalid media file extension".into()); }
            let input = base.join(format!("input.{}", extension));
            let audio = base.join("audio.wav");
            let output_prefix = base.join("transcript");
            let bytes = base64::engine::general_purpose::STANDARD.decode(file_base64).map_err(|e| e.to_string())?;
            fs::write(&input, bytes).map_err(|e| e.to_string())?;
            let conversion = Command::new(ffmpeg).args(["-nostdin", "-y", "-i"]).arg(&input).args(["-vn", "-ar", "16000", "-ac", "1", "-c:a", "pcm_s16le"]).arg(&audio).output().map_err(|e| e.to_string())?;
            if !conversion.status.success() { return Err(format!("Audio extraction failed: {}", String::from_utf8_lossy(&conversion.stderr).chars().take(700).collect::<String>())); }
            // Force CPU inference: bundled Windows builds must not depend on a working GPU backend.
            let recognition = Command::new(&whisper).arg("-ng").arg("-m").arg(&model).arg("-f").arg(&audio).arg("-osrt").arg("-of").arg(&output_prefix).arg("-nt").output().map_err(|e| e.to_string())?;
            if !recognition.status.success() {
                // Preserve the complete engine output for diagnosis without flooding screen readers.
                let log_dir = workspace_root(&app)?.join("Logs");
                fs::create_dir_all(&log_dir).map_err(|e| e.to_string())?;
                let log_path = unique_destination(&log_dir, "Local transcription failure.txt");
                let diagnostic = format!("Command: whisper-cli -ng -m [bundled model] -f [temporary audio] -osrt\nExit: {}\n\nSTDERR:\n{}\n\nSTDOUT:\n{}", recognition.status, String::from_utf8_lossy(&recognition.stderr), String::from_utf8_lossy(&recognition.stdout));
                fs::write(&log_path, diagnostic).map_err(|e| e.to_string())?;
                let tail = String::from_utf8_lossy(&recognition.stderr);
                let useful = tail.lines().rev().find(|line| { let lower = line.to_ascii_lowercase(); lower.contains("error") || lower.contains("failed") || lower.contains("abort") }).unwrap_or("Speech recognition exited unsuccessfully.");
                return Err(format!("Local speech recognition failed. {} Full diagnostic log: {}", useful.chars().take(220).collect::<String>(), log_path.display()));
            }
            let srt = fs::read_to_string(output_prefix.with_extension("srt")).map_err(|e| format!("Transcription completed without an SRT file: {}", e))?;
            if srt.trim().is_empty() { return Err("Speech recognition returned no spoken content.".into()); }
            Ok(srt)
        })();
        let _ = fs::remove_dir_all(&base);
        result
    }).await.map_err(|e| e.to_string())?
}

// Workspace files are independent of WebView localStorage and survive application upgrades.
// All paths are generated by the native process; the frontend never supplies a destination path.
fn workspace_root(app: &tauri::AppHandle) -> Result<PathBuf, String> {
    let documents = app.path().document_dir().map_err(|e| e.to_string())?;
    let root = documents.join("Open Door Accessible Assistant");
    fs::create_dir_all(&root).map_err(|e| format!("Unable to create workspace: {}", e))?;
    Ok(root)
}

fn safe_name(name: &str) -> String {
    let leaf = std::path::Path::new(name).file_name().and_then(|s| s.to_str()).unwrap_or("Imported file");
    let cleaned: String = leaf.chars().map(|c| if c.is_control() || "<>:\"/\\|?*".contains(c) { '_' } else { c }).collect();
    let cleaned = cleaned.trim_matches(|c| c == ' ' || c == '.');
    if cleaned.is_empty() { "Imported file".into() } else { cleaned.chars().take(160).collect() }
}

fn unique_destination(folder: &std::path::Path, name: &str) -> PathBuf {
    let first = folder.join(name);
    if !first.exists() { return first; }
    let path = std::path::Path::new(name);
    let stem = path.file_stem().and_then(|s| s.to_str()).unwrap_or("File");
    let ext = path.extension().and_then(|s| s.to_str()).unwrap_or("");
    for n in 2..100000 {
        let candidate = folder.join(if ext.is_empty() { format!("{} ({})", stem, n) } else { format!("{} ({}).{}", stem, n, ext) });
        if !candidate.exists() { return candidate; }
    }
    folder.join(format!("{}-{}", name, std::process::id()))
}

#[tauri::command]
fn workspace_location(app: tauri::AppHandle) -> Result<String, String> {
    Ok(workspace_root(&app)?.display().to_string())
}

#[tauri::command]
async fn workspace_import(app: tauri::AppHandle, file_name: String, file_base64: String) -> Result<String, String> {
    tauri::async_runtime::spawn_blocking(move || {
        let folder = workspace_root(&app)?.join("Sources");
        fs::create_dir_all(&folder).map_err(|e| e.to_string())?;
        let bytes = base64::engine::general_purpose::STANDARD.decode(file_base64).map_err(|e| e.to_string())?;
        let target = unique_destination(&folder, &safe_name(&file_name));
        fs::write(&target, bytes).map_err(|e| e.to_string())?;
        Ok(target.display().to_string())
    }).await.map_err(|e| e.to_string())?
}

#[tauri::command]
fn workspace_save_transcript(app: tauri::AppHandle, file_name: String, srt: String) -> Result<String, String> {
    if srt.trim().is_empty() { return Err("Cannot save an empty transcript".into()); }
    let folder = workspace_root(&app)?.join("Transcripts");
    fs::create_dir_all(&folder).map_err(|e| e.to_string())?;
    let original = safe_name(&file_name);
    let stem = std::path::Path::new(&original).file_stem().and_then(|s| s.to_str()).unwrap_or("Transcript");
    let target = unique_destination(&folder, &format!("{} transcript.srt", stem));
    fs::write(&target, srt.as_bytes()).map_err(|e| e.to_string())?;
    Ok(target.display().to_string())
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    tauri::Builder::default()
        .invoke_handler(tauri::generate_handler![transcription_engine_status, transcribe_local, workspace_location, workspace_import, workspace_save_transcript])
        .run(tauri::generate_context!())
        .expect("Unable to start Open Door Accessible Assistant");
}
